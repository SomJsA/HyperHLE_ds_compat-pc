//! Windows gameplay layouts for the three older editions with touch frontends.
//! The launcher identifies the archive; these hashes identify the ARM slice
//! actually mapped by the runtime (the phone and World archives are fat).

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum LegacyInputProfile {
    EarlyIpad,
    Iphone,
    World,
}

impl LegacyInputProfile {
    pub(crate) fn identify(bundle: &str, build: &str, digest: Option<[u8; 32]>) -> Option<Self> {
        const EARLY_IPAD: [u8; 32] = [
            0x28, 0x88, 0x8b, 0x16, 0xcf, 0x63, 0xe7, 0xb5, 0x48, 0xf1, 0x97, 0xd0, 0x46, 0xf7,
            0x1b, 0xb6, 0x58, 0xa0, 0xba, 0x05, 0xdd, 0x3f, 0xb3, 0x3d, 0x01, 0x5f, 0x64, 0xc8,
            0x20, 0x02, 0x2d, 0x2f,
        ];
        const IPHONE: [u8; 32] = [
            0x88, 0x4d, 0x4c, 0x2c, 0x6d, 0xfa, 0x86, 0xcb, 0x34, 0x35, 0x7b, 0x00, 0xd7, 0x1f,
            0xd6, 0x41, 0xdd, 0xdf, 0xf2, 0x6f, 0x1a, 0x9a, 0xfb, 0x82, 0xa8, 0x4c, 0xb9, 0x7e,
            0x46, 0x8b, 0x93, 0xf8,
        ];
        const WORLD: [u8; 32] = [
            0x53, 0x95, 0xdb, 0x93, 0x1d, 0x69, 0xe7, 0xec, 0x97, 0x87, 0xf2, 0x3b, 0x71, 0x2d,
            0x80, 0x2e, 0x86, 0xc5, 0xf6, 0x60, 0xc8, 0x86, 0x37, 0x63, 0x1d, 0xf4, 0x8b, 0xa1,
            0x20, 0xc8, 0x07, 0x3e,
        ];
        match (bundle, build, digest?) {
            ("com.ea.deadspace.ipad.bv", "1.0.3", EARLY_IPAD) => Some(Self::EarlyIpad),
            ("com.ea.deadspace.inc", "1.3.8", IPHONE) => Some(Self::Iphone),
            ("com.ea.deadspace.bv", "1.0.1", WORLD) => Some(Self::World),
            _ => None,
        }
    }
}
